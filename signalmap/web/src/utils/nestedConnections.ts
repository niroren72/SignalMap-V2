import type { ConnectionEvent } from '@shared/types';

export interface GroupedConnectionRow {
    primary: ConnectionEvent;
    children: ConnectionEvent[];
    groupKey: string;
    totalBytesIn: number;
    totalBytesOut: number;
    hasChildAnomaly: boolean;
    inboundCount: number;
    outboundCount: number;
}

/**
 * Determine which module plugin owns a given ConnectionEvent.
 */
export function getEventModuleId(e: ConnectionEvent): string {
    const explicitPlugin = (e as { source_plugin?: string }).source_plugin;
    if (explicitPlugin) {
        if (explicitPlugin === 'aws') return 'cloud';
        return explicitPlugin;
    }

    const collector = (e.source_collector || 'psutil_sockets').toLowerCase();
    if (
        collector === 'psutil_sockets' ||
        collector === 'windows_udp' ||
        collector === 'windows_dns' ||
        collector === 'windows_evtx' ||
        collector === 'socket' ||
        collector === 'netstat' ||
        collector === 'windows'
    ) {
        return 'windows';
    }
    if (collector.startsWith('salesforce')) return 'salesforce';
    if (collector.startsWith('macos')) return 'macos';
    if (collector.startsWith('hris') || collector.startsWith('workday')) return 'hris';
    if (collector.startsWith('cloud') || collector.startsWith('aws')) return 'cloud';
    if (collector.startsWith('okta')) return 'okta';
    return collector;
}

/**
 * Check if a ConnectionEvent belongs to the active module filter.
 */
export function matchesModule(e: ConnectionEvent, activeModule: string): boolean {
    if (!activeModule || activeModule === 'all') return true;
    const target = activeModule === 'aws' ? 'cloud' : activeModule;
    return getEventModuleId(e) === target;
}

/**
 * Check if a ConnectionEvent was generated by the Sample Data Ingester.
 */
export function isSampleEvent(e: ConnectionEvent, moduleId?: string): boolean {
    const id = e.id || '';
    const flagged = Boolean((e as { is_sample?: boolean }).is_sample);
    const isSampleId =
        flagged ||
        id.startsWith('sample-') ||
        id.startsWith('sf-evt-') ||
        id.startsWith('hris-evt-');
    if (!isSampleId) return false;
    if (!moduleId || moduleId === 'all') return true;
    return getEventModuleId(e) === (moduleId === 'aws' ? 'cloud' : moduleId);
}

/**
 * Normalize legacy San Francisco LAN fallback coordinates (37.7749, -122.4194 with country="LAN")
 * to the host's real local origin (e.g., Tel Aviv, Israel: 32.0853, 34.7818).
 */
export function normalizeEventGeoToOrigin(
    e: ConnectionEvent,
    origin: { lat: number; lng: number; city?: string; country?: string }
): ConnectionEvent {
    if (!e.geo) return e;
    const isLegacyLanFallback =
        (e.geo.country === 'LAN' || e.remote?.ip?.startsWith('192.168.') || e.remote?.ip?.startsWith('10.') || e.remote?.ip?.startsWith('224.') || e.remote?.ip?.startsWith('239.')) &&
        Math.abs((e.geo.lat ?? 0) - 37.7749) < 0.05 &&
        Math.abs((e.geo.lon ?? 0) - -122.4194) < 0.05;

    if (!isLegacyLanFallback) return e;

    return {
        ...e,
        geo: {
            ...e.geo,
            lat: origin.lat,
            lon: origin.lng,
            country: origin.country || 'IL',
            city: `${origin.city || 'Tel Aviv'} (Local LAN)`,
        },
    };
}

/**
 * Group flat ConnectionEvents into parent rows with nested child connections.
 * Events are grouped when they share:
 *  - An explicit `parent_id`, OR
 *  - The same `(moduleId, process_name, remote target [hostname or IP])`
 */
export function groupNestedEvents(events: ConnectionEvent[]): GroupedConnectionRow[] {
    const groups = new Map<string, ConnectionEvent[]>();
    const byId = new Map<string, ConnectionEvent>();
    const seenIds = new Set<string>();
    const uniqueEvents: ConnectionEvent[] = [];

    for (const e of events) {
        if (e.id) {
            if (seenIds.has(e.id)) continue;
            seenIds.add(e.id);
            byId.set(e.id, e);
        }
        uniqueEvents.push(e);
    }

    for (const e of uniqueEvents) {
        const parentId = (e as { parent_id?: string }).parent_id;
        let key: string;
        if (parentId && byId.has(parentId)) {
            const p = byId.get(parentId)!;
            const mod = getEventModuleId(p);
            const proc = (p.local?.process_name || 'System').toLowerCase();
            const remoteKey = (p.remote?.hostname || p.remote?.ip || 'local').toLowerCase();
            key = `${mod}::${proc}::${remoteKey}`;
        } else {
            const mod = getEventModuleId(e);
            const proc = (e.local?.process_name || 'System').toLowerCase();
            const remoteKey = (e.remote?.hostname || e.remote?.ip || 'local').toLowerCase();
            key = `${mod}::${proc}::${remoteKey}`;
        }

        const bucket = groups.get(key);
        if (bucket) {
            bucket.push(e);
        } else {
            groups.set(key, [e]);
        }
    }

    const result: GroupedConnectionRow[] = [];
    for (const [groupKey, list] of groups.entries()) {
        // Prefer an anomaly or non-child event as the primary parent row
        const sortedGroup = [...list].sort((a, b) => {
            const aParent = (a as { parent_id?: string }).parent_id ? 1 : 0;
            const bParent = (b as { parent_id?: string }).parent_id ? 1 : 0;
            if (aParent !== bParent) return aParent - bParent;
            const aAnom = a.anomaly?.is_anomaly ? 1 : 0;
            const bAnom = b.anomaly?.is_anomaly ? 1 : 0;
            if (aAnom !== bAnom) return bAnom - aAnom;
            return 0;
        });

        const primary = sortedGroup[0];
        const children = sortedGroup.slice(1);

        let totalBytesIn = 0;
        let totalBytesOut = 0;
        let hasChildAnomaly = false;
        let inboundCount = 0;
        let outboundCount = 0;

        for (const item of sortedGroup) {
            totalBytesIn += item.metrics?.bytes_in || 0;
            totalBytesOut += item.metrics?.bytes_out || 0;
            if (item.direction === 'inbound') inboundCount++;
            else outboundCount++;
        }
        for (const child of children) {
            if (child.anomaly?.is_anomaly) hasChildAnomaly = true;
        }

        result.push({
            primary,
            children,
            groupKey,
            totalBytesIn,
            totalBytesOut,
            hasChildAnomaly,
            inboundCount,
            outboundCount,
        });
    }

    return result;
}

